export type TKey = keyof (typeof DICTIONARY)["en"];

type Dict = typeof DICTIONARY["id"];

export type TParams = Record<string, string | number>;

export function translate(locale: AppLocale, key: TKey, params?: TParams): string {
 const dict = DICTIONARY[locale] as unknown as Dict;
 let text: string = dict[key] ?? DICTIONARY.id[key] ?? key;
 if (params) {
 for (const [name, value] of Object.entries(params)) {
 text = text.replaceAll(`{${name}}`, String(value));
 }
 }
 return text;
}

type Listener = () => void;

const listeners = new Set<Listener>();

let cachedRaw: string | null | undefined;
let cachedValue: AppLocale | undefined;

export function subscribeLocale(listener: Listener): () => void {
 listeners.add(listener);
 return () => {
 listeners.delete(listener);
 };
}

function notify(): void {
 listeners.forEach((listener) => listener());
}

export function getLocale(): AppLocale {
 if (typeof window === "undefined") return DEFAULT_LOCALE;

 const raw = window.localStorage.getItem(LOCALE_KEY);
 if (raw === cachedRaw) {
 return cachedValue ?? DEFAULT_LOCALE;
 }
 cachedRaw = raw;

 let parsed: AppLocale = DEFAULT_LOCALE;
 if (raw === "en") parsed = "en";
 cachedValue = parsed;
 return parsed;
}

export function setLocale(locale: AppLocale): void {
 if (typeof window === "undefined") return;
 window.localStorage.setItem(LOCALE_KEY, locale);
 cachedRaw = undefined;
 cachedValue = undefined;
 notify();
}